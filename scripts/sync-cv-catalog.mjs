#!/usr/bin/env node
import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
const sourcePath =
  process.env.CV_LAYERS_FILE ??
  path.resolve(root, '../cv/dist/js/cv-layers-5.5.js');
const cvRoot = process.env.CV_ROOT ?? path.resolve(root, '../cv');
const outputDir = path.join(root, 'src/layers/climateviewer');
const publicDir = path.join(root, 'public/cv');

const FAMILIES = Object.freeze({
  kml: { family: 'kml', role: 'overlay' },
  'arcgis-layer': { family: 'arcgis', role: 'overlay' },
  arcgis: { family: 'arcgis', role: 'overlay' },
  geojson: { family: 'geojson', role: 'overlay' },
  wms: { family: 'wms', role: 'overlay' },
  'nasa-gibs': { family: 'gibs', role: 'overlay', generatedUrl: true },
  'cartodb-layer': { family: 'cartodb', role: 'basemap' },
  'base-layer': { family: 'baseLayer', role: 'basemap' },
  bing: { family: 'bing', role: 'basemap', keyRequired: true },
});

const GIBS = Object.freeze({
  url: 'https://map1.vis.earthdata.nasa.gov/wmts-webmerc/wmts.cgi',
  format: 'image/jpeg',
  tileMatrixSetID: 'GoogleMapsCompatible_Level9',
  maximumLevel: 9,
});

const CATEGORY_LABELS = Object.freeze({
  Live: 'Live',
  weather: 'Weather',
  satellites: 'Satellites',
  pollution: 'Pollution',
  bigbrother: 'Big Brother',
  WXMOD: 'Weather Modification',
  electromagnetic: 'Electromagnetic',
  MRM: 'MyReadingMapped',
  other: 'Other',
  basemaps: 'Basemaps',
});

const slug = (value) =>
  String(value)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '') || 'layer';

const stripHtml = (value) =>
  String(value ?? '')
    .replace(/<img[^>]*>/gi, ' ')
    .replace(/<br\s*\/?>/gi, ' ')
    .replace(/<[^>]*>/g, '')
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&nbsp;/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();

const TOKEN_ALPHABET = '0123456789abcdefghijklmnopqrstuvwxyz';

/**
 * ClimateViewer layers take tokens from the far end of the two-character space,
 * so upstream allocations from the near end never collide with them.
 */
function* tokenCandidates() {
  for (let first = TOKEN_ALPHABET.length - 1; first >= 10; first -= 1) {
    for (let second = TOKEN_ALPHABET.length - 1; second >= 0; second -= 1) {
      yield `${TOKEN_ALPHABET[first]}${TOKEN_ALPHABET[second]}`;
    }
  }
}

function existingTokens() {
  const ledgerPath = path.join(root, 'src/data/layerStateTokenReservations.json');
  const rows = JSON.parse(fs.readFileSync(ledgerPath, 'utf8'));
  return { rows, occupied: new Set(rows.map(([, token]) => token)) };
}

function writeShareLinkLedger(layersInOrder) {
  // Only core allocations occupy the namespace: ClimateViewer tokens are
  // recomputed from the catalog each run, so they stay reproducible.
  const { occupied } = existingTokens();
  const tokens = new Map();
  const candidates = tokenCandidates();
  for (const layer of layersInOrder) {
    let token = candidates.next().value;
    while (occupied.has(token)) token = candidates.next().value;
    occupied.add(token);
    tokens.set(layer.id, token);
  }

  const cvRows = layersInOrder.map((layer) => [layer.id, tokens.get(layer.id)]);
  const ledgerPath = path.join(root, 'src/data/climateviewerTokenReservations.json');
  fs.writeFileSync(ledgerPath, `${JSON.stringify(cvRows, null, 0)}\n`);

  const registryPath = path.join(outputDir, 'layerState.generated.js');
  const entries = cvRows
    .map(
      ([id, token]) =>
        `  Object.freeze({ id: '${id}', token: '${token}', disposition: 'enabled-only' }),`,
    )
    .join('\n');
  fs.writeFileSync(
    registryPath,
    `// Generated by scripts/sync-cv-catalog.mjs. Do not edit.\nexport const CLIMATEVIEWER_LAYER_STATE_REGISTRY = Object.freeze([\n${entries}\n]);\n`,
  );
  const exhausted = cvRows.filter(([, token]) => !token);
  if (exhausted.length) throw new Error('Layer-state token namespace exhausted');
  console.log(
    `  share links: ${cvRows.length} tokens (${path.relative(root, registryPath)})`,
  );
}

function readDefinitions(file) {
  const source = fs.readFileSync(file, 'utf8');
  const match = source.match(/var layers\s*=\s*(\{[\s\S]*\});?\s*$/);
  if (!match) throw new Error(`No \`var layers = {...}\` in ${file}`);
  return { source, tree: new Function(`return ${match[1]}`)() };
}

const copied = new Set();
const missing = [];

function publishAsset(reference) {
  if (!reference || !reference.startsWith('/') || reference.startsWith('//'))
    return reference;
  const from = path.join(cvRoot, reference);
  const to = path.join(publicDir, reference);
  if (!fs.existsSync(from)) {
    missing.push(reference);
    return reference;
  }
  if (!copied.has(reference)) {
    fs.mkdirSync(path.dirname(to), { recursive: true });
    fs.copyFileSync(from, to);
    copied.add(reference);
  }
  return `/cv${reference}`;
}

const normalizeUrl = (value) => {
  const raw = String(value ?? '').trim();
  if (!raw) return '';
  if (raw.startsWith('/layers/') || raw.startsWith('/img/'))
    return publishAsset(raw);
  if (raw.startsWith('//')) return `https:${raw}`;
  return raw;
};

const { tree: definitions } = readDefinitions(sourcePath);
const layers = {};
const children = [];
const folderMeta = new Map();
const usedIds = new Set();
const duplicateCvIds = [];

function walk(node, categoryPath, target) {
  if (Array.isArray(node)) {
    for (const child of node) walk(child, categoryPath, target);
    return;
  }
  if (!node || typeof node !== 'object') return;

  if (node.T) {
    target.push(defineLayer(node, categoryPath));
    return;
  }

  const label = stripHtml(node.N ?? path[categoryPath.length - 1] ?? 'Layers');
  const folder = {
    kind: 'folder',
    name: label,
    icon: node.icon ?? '',
    children: [],
  };
  target.push(folder);
  folderMeta.set(folder, { categoryPath, label });
  for (const [key, value] of Object.entries(node)) {
    if (key === 'N' || key === 'icon' || key === 'I' || key === '>') {
      if (key === '>') walk(value, categoryPath, folder.children);
      continue;
    }
    walk(value, [...categoryPath, key], folder.children);
  }
}

function buildProvider(mapping, url, node) {
  const sublayers = String(node.L ?? '')
    .split(',')
    .map((entry) => entry.trim())
    .filter(Boolean);
  switch (mapping.family) {
    case 'kml':
      return { kind: 'kml', url, proxy: node.P === true };
    case 'geojson':
      return { kind: 'geojson', url };
    case 'arcgis':
      return { kind: 'arcgis', url, sublayers };
    case 'wms':
      return {
        kind: 'wms',
        url,
        layers: sublayers,
        format: 'image/png',
        transparent: true,
      };
    case 'gibs':
      return {
        kind: 'wmts',
        url,
        layer: String(node.I ?? ''),
        format: GIBS.format,
        tileMatrixSetID: GIBS.tileMatrixSetID,
        maximumLevel: GIBS.maximumLevel,
        time: true,
      };
    case 'cartodb':
      return { kind: 'urlTemplate', url };
    case 'baseLayer':
      return { kind: 'osm', url };
    default:
      return { kind: 'bing', imagerySet: String(node.G ?? '') };
  }
}

function defineLayer(node, categoryPath) {
  const cvId = String(node.I ?? 'unknown');
  const mapping = FAMILIES[String(node.T)] ?? FAMILIES.kml;
  const base = `cv-${slug(categoryPath[0] ?? 'other')}-${slug(cvId)}`;
  let id = base;
  if (usedIds.has(id)) {
    duplicateCvIds.push(cvId);
    let suffix = 2;
    while (usedIds.has(`${base}-${suffix}`)) suffix += 1;
    id = `${base}-${suffix}`;
  }
  usedIds.add(id);

  const sublayers = String(node.L ?? '')
    .split(',')
    .map((entry) => entry.trim())
    .filter(Boolean);

  const url = mapping.generatedUrl ? GIBS.url : normalizeUrl(node.G);
  const layer = {
    id,
    cvId,
    name: stripHtml(node.N ?? cvId),
    type: node.T,
    family: mapping.family,
    role: mapping.role,
    url,
    provider: buildProvider(mapping, url, node),
    sublayers,
    category: categoryPath.map((key) => CATEGORY_LABELS[key] ?? key),
    categoryKey: categoryPath[0] ?? 'other',
    description: stripHtml(node.S).slice(0, 600),
    sourceUrl: normalizeUrl(node.U),
    markerIcon: normalizeUrl(node.MI ?? ''),
    markerScale: Number(node.MS) || 1,
    flags: {
      large: node.H === true,
      new: node.NL === true,
      timeline: node.C === true,
      proxy: node.P === true,
      noFeatures: node.X === true,
      zoomTo: node.Z === true,
      threeOnly: node.TRD === true,
      leafletOnly: node.TWD === true,
    },
  };
  layers[id] = layer;
  return { kind: 'layer', id };
}

for (const [key, value] of Object.entries(definitions)) {
  if (key === 'I' || key === 'N') continue;
  if (value && typeof value === 'object' && !Array.isArray(value))
    walk(value, [key], children);
}

for (const folder of folderMeta.keys()) {
  if (folder.children.length === 1 && folder.children[0].kind === 'folder') {
    folder.collapsed = true;
  }
}

const collect = (nodes, out = []) => {
  for (const node of nodes) {
    if (node.kind === 'layer') out.push(layers[node.id]);
    else collect(node.children, out);
  }
  return out;
};

const all = collect(children);
const problems = [];
if (all.length < 400) problems.push(`only ${all.length} layers extracted`);
if (all.length !== Object.keys(layers).length)
  problems.push('layer table and tree disagree');
for (const layer of all) {
  if (!layer.url && layer.family !== 'bing')
    problems.push(`${layer.id}: no url`);
  if (!layer.category.length) problems.push(`${layer.id}: no category`);
  if (!layer.provider) problems.push(`${layer.id}: no provider`);
}
if (missing.length) problems.push(`${missing.length} missing assets: ${missing.slice(0, 3)}`);

if (problems.length) {
  console.error(`✖ sync-cv-catalog: ${problems.length} problem(s)`);
  for (const problem of problems.slice(0, 20)) console.error(`  - ${problem}`);
  process.exit(1);
}

fs.mkdirSync(outputDir, { recursive: true });
const catalogPath = path.join(outputDir, 'catalog.json');
fs.writeFileSync(
  catalogPath,
  `${JSON.stringify(
    {
      version: 1,
      generatedFrom: path.relative(root, sourcePath),
      tree: children,
      layers,
    },
    null,
    0,
  )}\n`,
);

const byFamily = {};
const byCategory = {};
for (const layer of all) {
  byFamily[layer.family] = (byFamily[layer.family] ?? 0) + 1;
  byCategory[layer.categoryKey] = (byCategory[layer.categoryKey] ?? 0) + 1;
}
const local = all.filter((layer) => layer.url.startsWith('/cv/')).length;
const size = (fs.statSync(catalogPath).size / 1024).toFixed(1);

writeShareLinkLedger(all);

console.log(`✓ ${all.length} layers → ${path.relative(root, catalogPath)} (${size} KB)`);
console.log(`  families: ${JSON.stringify(byFamily)}`);
console.log(`  categories: ${JSON.stringify(byCategory)}`);
console.log(`  local assets: ${local} layers, ${copied.size} files copied`);
console.log(`  duplicate cvIds resolved: ${duplicateCvIds.length ? duplicateCvIds.join(', ') : 'none'}`);
