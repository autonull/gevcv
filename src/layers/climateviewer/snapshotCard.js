import { t } from '../../i18n/index.js';

export const SNAPSHOT_WIDTH = 1000;
export const SNAPSHOT_HEIGHT = 620;
export const SNAPSHOT_MAX_LAYERS = 10;

function sourceHost(layer) {
  const metadata = layer?.metadata ?? {};
  const url =
    metadata.sourceUrl || metadata.provider?.url || metadata.providerUrl || '';
  if (!url) return '';
  try {
    return new URL(url, 'https://gevcv.local').host || '';
  } catch {
    return (
      String(url)
        .replace(/^https?:\/\//, '')
        .split('/')[0] || ''
    );
  }
}

/** Build the printable card model from the enabled CV layer list. */
export function buildClimateViewerSnapshotModel(
  layers,
  { now = new Date(), maxLayers = SNAPSHOT_MAX_LAYERS } = {},
) {
  const all = Array.isArray(layers) ? layers : [];
  const shown = all.slice(0, Math.max(1, maxLayers));
  const attribution = [];
  for (const layer of shown) {
    const host = sourceHost(layer);
    if (host && !attribution.includes(host)) attribution.push(host);
  }
  return {
    // i18n-ignore: product branding
    title: 'God’s Eye View · ClimateViewer Atlas',
    timestamp: `${new Date(now).toISOString().slice(0, 19).replace('T', ' ')} UTC`,
    layerCount: all.length,
    layers: shown.map((layer) => ({
      name: String(layer.name ?? layer.id ?? 'Layer'),
      source: sourceHost(layer),
    })),
    omitted: Math.max(0, all.length - shown.length),
    attribution: attribution.slice(0, 8),
    // i18n-ignore: product credit
    credit: 'ClimateViewer (climateviewer.org)',
    // i18n-ignore: product branding
    footer: 'Generated by God’s Eye View',
  };
}

function wrapText(context, text, maxWidth, maxLines) {
  const words = String(text).split(/\s+/);
  const lines = [];
  let line = '';
  for (const word of words) {
    const next = line ? `${line} ${word}` : word;
    if (context.measureText(next).width <= maxWidth || !line) {
      line = next;
      continue;
    }
    lines.push(line);
    line = word;
    if (lines.length === maxLines - 1) break;
  }
  if (line && lines.length < maxLines) lines.push(line);
  return lines;
}

/** Draw the card onto a square-pixel canvas and return it. */
export function renderClimateViewerSnapshot(
  model,
  { documentRef = globalThis.document } = {},
) {
  const canvas = documentRef.createElement('canvas');
  canvas.width = SNAPSHOT_WIDTH;
  canvas.height = SNAPSHOT_HEIGHT;
  const context = canvas.getContext('2d');
  if (!context) return canvas;

  context.fillStyle = '#080d13';
  context.fillRect(0, 0, SNAPSHOT_WIDTH, SNAPSHOT_HEIGHT);
  context.fillStyle = '#12202c';
  context.fillRect(0, 0, 10, SNAPSHOT_HEIGHT);
  context.fillStyle = '#78dca0';
  context.fillRect(10, 0, 3, SNAPSHOT_HEIGHT);

  context.fillStyle = '#f2f6fa';
  context.font = '600 30px ui-sans-serif, system-ui, sans-serif';
  context.fillText(model.title, 46, 62);
  context.fillStyle = '#8fc8ff';
  context.font = '13px ui-monospace, SFMono-Regular, Menlo, monospace';
  context.fillText(model.timestamp, 46, 88);

  context.fillStyle = '#9fb2c4';
  context.font = '12px ui-monospace, SFMono-Regular, Menlo, monospace';
  context.fillText(
    `${model.layerCount} enabled ${model.layerCount === 1 ? 'layer' : 'layers'}`,
    46,
    122,
  );

  let y = 162;
  for (const layer of model.layers) {
    context.fillStyle = '#e8eef5';
    context.font = '15px ui-sans-serif, system-ui, sans-serif';
    const titleLines = wrapText(context, layer.name, 620, 2);
    for (const line of titleLines) {
      context.fillText(line, 46, y);
      y += 20;
    }
    if (layer.source) {
      context.fillStyle = '#7f93a7';
      context.font = '11px ui-monospace, SFMono-Regular, Menlo, monospace';
      context.fillText(layer.source, 46, y);
      y += 18;
    }
    y += 6;
    if (y > 440) break;
  }
  if (model.omitted) {
    context.fillStyle = '#f0b46c';
    context.font = '12px ui-monospace, SFMono-Regular, Menlo, monospace';
    context.fillText(`+${model.omitted} more`, 46, y + 4);
  }

  context.strokeStyle = 'rgb(255 255 255 / 14%)';
  context.beginPath();
  context.moveTo(46, 494);
  context.lineTo(SNAPSHOT_WIDTH - 46, 494);
  context.stroke();

  context.fillStyle = '#9fb2c4';
  context.font = '11px ui-monospace, SFMono-Regular, Menlo, monospace';
  const sources = model.attribution.join(' · ') || 'No external attribution';
  const sourceLines = wrapText(context, `Sources: ${sources}`, 770, 2);
  sourceLines.forEach((line, index) =>
    context.fillText(line, 46, 522 + index * 16),
  );

  context.fillStyle = '#78dca0';
  context.font = '12px ui-monospace, SFMono-Regular, Menlo, monospace';
  context.fillText(model.credit, 46, 576);
  context.fillStyle = '#6c7f92';
  context.fillText(model.footer, 46, 596);
  return canvas;
}

/** Show the card in a modal with a PNG download; return a cleanup handle. */
export function openClimateViewerSnapshot(
  model,
  {
    documentRef = globalThis.document,
    downloadName = `gev-climateviewer-${model.timestamp.slice(0, 10)}.png`,
  } = {},
) {
  const canvas = renderClimateViewerSnapshot(model, { documentRef });
  const overlay = documentRef.createElement('div');
  overlay.className = 'snapshot-overlay';
  overlay.setAttribute('role', 'dialog');
  overlay.setAttribute('aria-modal', 'true');
  overlay.setAttribute('aria-label', t('ClimateViewer snapshot'));

  const dialog = documentRef.createElement('div');
  dialog.className = 'snapshot-dialog';
  const image = documentRef.createElement('img');
  image.className = 'snapshot-card';
  image.alt = 'ClimateViewer atlas snapshot card';
  image.src = canvas.toDataURL('image/png');
  const actions = documentRef.createElement('div');
  actions.className = 'snapshot-actions';
  const download = documentRef.createElement('a');
  download.className = 'snapshot-download';
  download.href = image.src;
  download.download = downloadName;
  download.textContent = t('Download PNG');
  const close = documentRef.createElement('button');
  close.type = 'button';
  close.className = 'snapshot-close';
  close.textContent = t('Close');
  actions.append(download, close);
  dialog.append(image, actions);
  overlay.append(dialog);
  documentRef.body.appendChild(overlay);

  const dismiss = () => overlay.remove();
  close.addEventListener('click', dismiss);
  overlay.addEventListener('click', (event) => {
    if (event.target === overlay) dismiss();
  });
  return { overlay, dialog, canvas, close: dismiss };
}
